    public static function normalize(?string $name): ?string
    {
        if ($name === null) {
            return null;
        }
        $name = trim(str_replace(['ي', 'ك'], ['ی', 'ک'], $name));

        return $name === '' ? null : $name;
    }

    /**
     * @return list<string>
     */
    public static function neighbors(?string $province): array
    {
        $province = self::normalize($province);
        if ($province === null) {
            return [];
        }

        return self::NEIGHBORS[$province] ?? [];
    }

    /**
     * عبارت ORDER BY خام + بایندینگ‌ها برای اولویت: شهر → استان → همسایه → سایر.
     *
     * @return array{0: string, 1: list<string>}
     */
    public static function assignOrderSql(?string $province, ?string $city): array
    {
        $province = self::normalize($province);
        $city = self::normalize($city);
        if ($province === null && $city === null) {
            return ['id asc', []];
        }

        $neighbors = self::neighbors($province);
        $bindings = [];
        $parts = [];

        if ($city !== null && $province !== null) {
            $parts[] = 'WHEN city = ? AND province = ? THEN 0';
            $bindings[] = $city;
            $bindings[] = $province;
        } elseif ($city !== null) {
            $parts[] = 'WHEN city = ? THEN 0';
            $bindings[] = $city;
        }

        if ($province !== null) {
            $parts[] = 'WHEN province = ? THEN 1';
            $bindings[] = $province;
        }

        if ($neighbors !== []) {
            $placeholders = implode(',', array_fill(0, count($neighbors), '?'));
            $parts[] = "WHEN province IN ({$placeholders}) THEN 2";
            foreach ($neighbors as $n) {
                $bindings[] = $n;
            }
        }

        $case = 'CASE '.implode(' ', $parts).' ELSE 3 END asc, id asc';

        return [$case, $bindings];
    }
